interface FakeSupaConfig {
  existingChunks?: Array<{ content: string }>;
  insertChunksError?: { message: string } | null;
  registryRowAutoGenerated?: boolean;
  parentInsertReturning?: Array<{ id: number; metadata: Record<string, unknown> }>;
  rpcError?: { message: string } | null;
}

function setupSupabase(config: FakeSupaConfig = {}) {
  const insertedChildChunks: unknown[][] = [];
  const insertedParentChunks: unknown[][] = [];
  const deletes: string[] = [];

  // dubai_code_chunks builder
  const dubaiBuilder = {
    select: vi.fn((_cols: string) => ({
      eq: vi.fn().mockResolvedValue({ data: config.existingChunks ?? [], error: null }),
    })),
    insert: vi.fn((rows: unknown[]) => {
      insertedChildChunks.push(rows);
      return Promise.resolve({ error: config.insertChunksError ?? null });
    }),
    delete: vi.fn(() => ({
      eq: vi.fn().mockImplementation(async () => {
        deletes.push('dubai_code_chunks');
        return { error: null };
      }),
    })),
  };

  // parent_chunks builder
  const parentBuilder = {
    delete: vi.fn(() => ({
      eq: vi.fn().mockImplementation(async () => {
        deletes.push('parent_chunks');
        return { error: null };
      }),
    })),
    insert: vi.fn((rows: unknown[]) => {
      insertedParentChunks.push(rows);
      return {
        select: vi.fn().mockResolvedValue({
          data: config.parentInsertReturning ?? (rows as Array<{ metadata: { startPage: number; endPage: number } }>).map((r, i) => ({
            id: 100 + i,
            metadata: r.metadata,
          })),
          error: null,
        }),
      };
    }),
  };

  // document_registry builder
  const registryBuilder = {
    select: vi.fn(() => ({
      eq: vi.fn(() => ({
        single: vi.fn().mockResolvedValue({
          data: { keywords_auto_generated: config.registryRowAutoGenerated ?? true },
          error: null,
        }),
      })),
    })),
    update: vi.fn(() => ({
      eq: vi.fn().mockResolvedValue({ error: null }),
    })),
  };

  const fromImpl = (table: string) => {
    if (table === 'dubai_code_chunks') return dubaiBuilder;
    if (table === 'parent_chunks') return parentBuilder;
    if (table === 'document_registry') return registryBuilder;
    // document_trees fallback (used by saveDocumentTreeDirect)
    return {
      upsert: vi.fn().mockResolvedValue({ error: null }),
    };
  };

  const from = vi.fn(fromImpl);
  const rpc = vi.fn().mockResolvedValue({ error: config.rpcError ?? null });

  vi.mocked(createAdminClient).mockReturnValue({
    from,
    rpc,
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
  } as any);

  return { from, rpc, insertedChildChunks, insertedParentChunks, deletes };
}

function makeParser(opts: {
  totalPages?: number;
  pages?: Array<{ pageNumber: number; text: string }>;
  flatTOC?: Array<{ title: string; section: string; level: number; pageNumber: number }>;
} = {}): FakeParser {
  const pages = opts.pages ?? [
    { pageNumber: 1, text: 'Section 1: Introduction. This is the first page of content.' },
    { pageNumber: 2, text: 'Section 2: Requirements. This describes building requirements.' },
  ];
  return {
    totalPages: opts.totalPages ?? pages.length,
    extractTOC: async () => ({ flatTOC: opts.flatTOC ?? [] }),
    getAllPagesText: async () => pages,
    findSectionForPage: (_page: number) => ({
      section: '1',
      sectionTitle: 'Intro',
      sectionPath: ['Intro'],
    }),
    detectContentType: (_text: string) => 'text',
    close: async () => {},
  };
}

