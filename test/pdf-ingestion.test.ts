describe('splitWithPageTracking', () => {
  it('produces chunks tagged with the originating page numbers', async () => {
    const longText = (n: number) => 'word '.repeat(150) + `marker${n}`;
    const pages = [
      { pageNumber: 1, text: longText(1) },
      { pageNumber: 2, text: longText(2) },
    ];
    const parser = makeParser({ pages });
    const chunks = await splitWithPageTracking(pages as never, parser as never);
    expect(chunks.length).toBeGreaterThan(0);
    for (const c of chunks) {
      expect(c.startPage).toBeGreaterThanOrEqual(1);
      expect(c.endPage).toBeGreaterThanOrEqual(c.startPage);
      expect(c.endPage).toBeLessThanOrEqual(2);
    }
  });

  it('skips empty pages and chunks shorter than MIN_CHUNK_LENGTH', async () => {
    const pages = [
      { pageNumber: 1, text: '' },
      { pageNumber: 2, text: 'tiny' }, // shorter than MIN_CHUNK_LENGTH=50
    ];
    const parser = makeParser({ pages });
    const chunks = await splitWithPageTracking(pages as never, parser as never);
    expect(chunks.length).toBe(0);
  });
});

