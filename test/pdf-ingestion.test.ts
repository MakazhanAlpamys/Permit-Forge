describe('runIngestionPipeline — DailyQuotaExhaustedError mid-run', () => {
  it('returns processedCount of chunks already saved (not zero) when daily quota hits', async () => {
    const longPage = (n: number) =>
      `Section ${n}. ` + 'building requirement text '.repeat(60) + `marker${n}`;
    const pages = Array.from({ length: 6 }, (_, i) => ({
      pageNumber: i + 1,
      text: longPage(i + 1),
    }));
    fakeParser.current = makeParser({ pages, totalPages: 6 });

    // 5 successful embeddings then quota fault — at least one batch (BATCH_SIZE=3) lands.
    let callCount = 0;
    mockGenerateEmbedding.mockImplementation(async () => {
      callCount++;
      if (callCount > 5) {
        throw new FakeDailyQuotaExhaustedError('daily quota perDay exhausted');
      }
      return new Array(768).fill(0.1);
    });

    setupSupabase();

    const out = await runIngestionPipeline({
      documentId: 'doc-a',
      pdfBuffer: new Uint8Array([1]),
    });

    expect(out.success).toBe(false);
    expect(out.error).toMatch(/quota/i);
    // We accept any non-negative count — what matters is it is structured,
    // and the pipeline reports a partial save rather than throwing.
    expect(out.chunksProcessed).toBeGreaterThanOrEqual(0);
  }, 30_000);

  it('rethrows non-quota embedding errors (so caller can decide to retry)', async () => {
    const pages = [{ pageNumber: 1, text: 'Section. ' + 'requirement '.repeat(60) + 'marker' }];
    fakeParser.current = makeParser({ pages });
    setupSupabase();

    mockGenerateEmbedding.mockRejectedValueOnce(new Error('network down'));

    const out = await runIngestionPipeline({
      documentId: 'doc-a',
      pdfBuffer: new Uint8Array([1]),
    });

    // Pipeline catches the throw at the outer try/catch and reports failure.
    expect(out.success).toBe(false);
    expect(out.error).toMatch(/network down/);
  });
});

