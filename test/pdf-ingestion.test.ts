describe('runIngestionPipeline — resume skip path', () => {
  it('short-circuits when every chunk is already in the DB', async () => {
    const pages = [{ pageNumber: 1, text: 'A '.repeat(200) + 'marker' }];
    fakeParser.current = makeParser({ pages });

    // Compute what splitWithPageTracking would emit, then pre-seed existingChunks.
    const expected = await splitWithPageTracking(pages as never, fakeParser.current as never);
    const existing = expected.map((c) => ({ content: c.content }));

    setupSupabase({ existingChunks: existing });

    // generateEmbedding should NOT be called when nothing needs ingesting.
    const out = await runIngestionPipeline({
      documentId: 'doc-a',
      pdfBuffer: new Uint8Array([1]),
    });

    expect(out.success).toBe(true);
    expect(mockGenerateEmbedding).not.toHaveBeenCalled();
    expect(out.chunksProcessed).toBe(existing.length);
  });

  it('clears stale chunks when PDF content has changed', async () => {
    const pages = [{ pageNumber: 1, text: 'New content. ' + 'fresh '.repeat(80) + 'marker' }];
    fakeParser.current = makeParser({ pages });

    const supa = setupSupabase({
      // Old chunk no longer matches anything in the new PDF
      existingChunks: [{ content: 'OLD STALE CHUNK that does not match new PDF' }],
    });

    const out = await runIngestionPipeline({
      documentId: 'doc-a',
      pdfBuffer: new Uint8Array([1]),
    });

    expect(out.success).toBe(true);
    // dubai_code_chunks.delete should have been invoked to clear old chunks
    expect(supa.deletes.includes('dubai_code_chunks')).toBe(true);
  });
});

