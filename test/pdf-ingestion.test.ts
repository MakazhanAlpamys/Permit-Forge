describe('runIngestionPipeline — happy path', () => {
  it('embeds child chunks, inserts parents, and links child→parent by page overlap', async () => {
    const pages = [
      { pageNumber: 1, text: 'Building Code Section 1. ' + 'lorem ipsum '.repeat(80) },
      { pageNumber: 2, text: 'Section 2 fire safety requirements. ' + 'dolor sit '.repeat(80) },
    ];
    fakeParser.current = makeParser({ pages, totalPages: 2 });

    const { rpc, insertedChildChunks, insertedParentChunks } = setupSupabase();

    const events: string[] = [];
    const out = await runIngestionPipeline({
      documentId: 'building-code-1',
      pdfBuffer: new Uint8Array([0x25, 0x50, 0x44, 0x46]),
      onProgress: async (p) => {
        events.push(p.stage);
      },
    });

    expect(out.success).toBe(true);
    expect(out.chunksProcessed).toBeGreaterThan(0);
    expect(out.pagesProcessed).toBe(2);

    // Parent chunks were inserted at least once (for non-trivial text)
    expect(insertedParentChunks.length).toBeGreaterThan(0);
    // Child chunks were inserted at least once
    expect(insertedChildChunks.length).toBeGreaterThan(0);

    // Every inserted child has document_name set to the documentId
    for (const batch of insertedChildChunks) {
      for (const rec of batch as Array<{ document_name: string; parent_id: number | null }>) {
        expect(rec.document_name).toBe('building-code-1');
      }
    }

    // At least one child should have a parent_id (page-overlap link succeeded)
    const allChildren = insertedChildChunks.flat() as Array<{ parent_id: number | null }>;
    const linked = allChildren.filter((c) => c.parent_id !== null);
    expect(linked.length).toBeGreaterThan(0);

    // save_document_tree RPC was invoked with the typed argument shape.
    // E (v1.4.0 Part E): tightened from expect.any(Object) — a rename of any
    // of the three snake_case params would silently keep the old test green.
    expect(rpc).toHaveBeenCalledWith('save_document_tree', expect.objectContaining({
      p_document_name: expect.any(String),
      p_total_pages: expect.any(Number),
      p_tree_data: expect.any(Array),
    }));

    // Stages walked through expected lifecycle
    expect(events).toContain('parsing');
    expect(events).toContain('extracting');
    expect(events).toContain('splitting');
    expect(events).toContain('embedding');
    expect(events).toContain('complete');
  }, 20_000);

  it('persists extracted keywords when keywords_auto_generated is not false', async () => {
    fakeParser.current = makeParser();
    mockExtractKeywords.mockReturnValueOnce({
      keywords: ['fire', 'safety'],
      categories: ['building'],
    });
    const supa = setupSupabase({ registryRowAutoGenerated: true });

    await runIngestionPipeline({
      documentId: 'doc-a',
      pdfBuffer: new Uint8Array([1, 2, 3]),
    });

    // document_registry.update was called with keywords + categories
    const registryFromCalls = supa.from.mock.calls.filter((c) => c[0] === 'document_registry');
    expect(registryFromCalls.length).toBeGreaterThan(0);
    // v1.7.0 Part B: invalidation now flows through the centralized helper,
    // scoped to the document just ingested.
    expect(mockInvalidateAll).toHaveBeenCalledWith('doc-a');
  });

  it('does NOT overwrite admin-edited keywords when keywords_auto_generated=false', async () => {
    fakeParser.current = makeParser();
    mockExtractKeywords.mockReturnValueOnce({
      keywords: ['fire'],
      categories: ['building'],
    });
    const supa = setupSupabase({ registryRowAutoGenerated: false });

    await runIngestionPipeline({
      documentId: 'doc-a',
      pdfBuffer: new Uint8Array([1]),
    });

    // No update of registry keywords should happen
    const registryBuilder = supa.from.mock.results.find(
      (r) => supa.from.mock.calls[supa.from.mock.results.indexOf(r)]?.[0] === 'document_registry',
    )?.value as { update: { mock: { calls: unknown[][] } } };
    // update should NOT have been called (the cache invalidators stay quiet too)
    expect(registryBuilder.update).toBeDefined();
    expect(registryBuilder.update.mock.calls.length).toBe(0);
    expect(mockInvalidateRegistry).not.toHaveBeenCalled();
  });
});

