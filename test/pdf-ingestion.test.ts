// ============================================================================
// E10 — lib/pdf-ingestion.ts coverage
// ============================================================================
// runIngestionPipeline orchestrates 7 stages and 3 collaborators (PDFParser,
// generateEmbedding, supabase). We mock the collaborators and drive the
// orchestrator through:
//   - happy-path full ingest with parent/child linking
//   - resume skip path (some chunks already exist)
//   - stale-chunk clear path (PDF content changed)
//   - DailyQuotaExhaustedError mid-run preserves processedCount
//   - batch insert error mid-run preserves processedCount
//   - advisory-lock collision proxy: registry row is_active=false → action layer
//     refuses to enter the pipeline (the in-pipeline lock is enforced by
//     try_start_ingestion RPC, exercised in actions/documents.ts tests; this
//     suite verifies the pipeline contract on its inputs.)
//   - empty PDF (no extractable text) short-circuits to "nothing to do"
//   - missing inputs (no buffer + no path) returns failure
//   - createPDFParser throw bubbles up as failure result
// ============================================================================

