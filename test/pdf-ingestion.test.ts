// ============================================================================
// Advisory-lock collision proxy
// ============================================================================
// The runIngestionPipeline function itself does not call try_start_ingestion —
// that's the action-layer guard (D19). The pipeline assumes its caller has
// already acquired the lock. We pin the contract with an explicit test: if
// the pipeline is invoked with a valid documentId and no DB lock, it proceeds.
// The companion test (collision case) lives in test/ingest-pdf-action.test.ts
// where the registry / action layer is exercised.
// ============================================================================

describe('runIngestionPipeline — advisory-lock contract', () => {
  it('does not call try_start_ingestion RPC (caller owns the lock)', async () => {
    const pages = [{ pageNumber: 1, text: 'Body. ' + 'word '.repeat(80) + 'marker' }];
    fakeParser.current = makeParser({ pages });
    const supa = setupSupabase();

    await runIngestionPipeline({
      documentId: 'doc-a',
      pdfBuffer: new Uint8Array([1]),
    });

    const rpcCallNames = supa.rpc.mock.calls.map((c) => c[0]);
    expect(rpcCallNames).not.toContain('try_start_ingestion');
  });
});
